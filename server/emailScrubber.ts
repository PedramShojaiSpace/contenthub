export interface EmailValidationResult {
  valid: boolean;
  reason?: string;
}

/**
 * Validates an email address.
 * Returns { valid: true } for clean emails.
 * Returns { valid: false, reason: "..." } for disposable or malformed emails.
 */
export function validateEmail(email: string): EmailValidationResult {
  if (!email || typeof email !== "string") {
    return { valid: false, reason: "Email is required" };
  }

  const trimmed = email.trim().toLowerCase();

  // Basic format check
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  if (!emailRegex.test(trimmed)) {
    return { valid: false, reason: "Invalid email format" };
  }

  const parts = trimmed.split("@");
  if (parts.length !== 2) {
    return { valid: false, reason: "Invalid email format" };
  }

  const domain = parts[1];

  // Check against disposable domain list
  if (DISPOSABLE_DOMAINS.has(domain)) {
    return {
      valid: false,
      reason: "Please use a permanent email address — temporary/disposable emails are not accepted.",
    };
  }

  // Check for suspicious patterns in the domain
  // e.g. domains with random characters like "sigismail.com" patterns
  const suspiciousPatterns = [
    /^\d+min(ute)?mail/i,   // 10minutemail variants
    /^temp/i,               // temp* domains
    /^trash/i,              // trash* domains
    /^spam/i,               // spam* domains
    /^fake/i,               // fake* domains
    /^throw/i,              // throwaway variants
    /^dispos/i,             // disposable variants
    /^guerrilla/i,          // guerrillamail variants
  ];

  for (const pattern of suspiciousPatterns) {
    if (pattern.test(domain)) {
      return {
        valid: false,
        reason: "Please use a permanent email address — temporary/disposable emails are not accepted.",
      };
    }
  }

  return { valid: true };
}
